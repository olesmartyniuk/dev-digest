/** Constants for the ci module (SPEC-05 — Export to CI). */

import type { CiTrigger } from '@devdigest/shared';

/** Branch the export PR is opened from. Never the default branch (AC-15). */
export const CI_BRANCH = 'devdigest/ci';
export const CI_PR_TITLE = 'Add DevDigest CI review';
export const CI_COMMIT_MESSAGE = 'chore(ci): add DevDigest CI review';

/** Workflow artifacts are named `devdigest-result-<agentSlug>-<run_id>-<run_attempt>`. */
export const ARTIFACT_PREFIX = 'devdigest-result-';
/** The file inside the artifact the runner writes. */
export const RESULT_FILE = 'devdigest-result.json';
/** Larger result files are ignored (never downloaded into memory). */
export const RESULT_MAX_BYTES = 256 * 1024;

/** Paths written into the target repository. */
export const CI_PATHS = {
  agent: (slug: string) => `.devdigest/agents/${slug}.yaml`,
  skill: (slug: string) => `.devdigest/skills/${slug}.md`,
  memory: '.devdigest/memory.jsonl',
  runner: '.devdigest/runner/agent-runner.cjs',
  workflow: (slug: string) => `.github/workflows/devdigest-${slug}.yml`,
} as const;

/** Canonical order of `pull_request.types` in the generated workflow. */
export const TRIGGER_ORDER: CiTrigger[] = ['opened', 'synchronize', 'reopened'];

/** Max CI run rows returned by the list endpoints. */
export const CI_RUNS_LIMIT = 200;

/** Per-route cap on install + sync (each hits the GitHub API). */
export const CI_RATE_LIMIT = { max: 10, timeWindow: '1 minute' } as const;

/** Header comment of the generated manifest. */
export const MANIFEST_HEADER =
  '# Generated by DevDigest — validated by the agent-runner against the shared AgentManifest schema.';

/** Generic user-facing errors. */
export const PROVIDER_UNSUPPORTED_MESSAGE =
  'Export to CI supports OpenRouter agents only. Switch this agent to an OpenRouter model to export it.';
export const INSTALL_FAILED_MESSAGE =
  'Could not open the pull request on GitHub. Check the GitHub token in Settings and try again, or download the files as a zip.';
export const SYNC_FAILED_PREFIX = 'Could not fetch CI results from GitHub';

/** Stable error code for a non-OpenRouter agent. */
export const ERR_PROVIDER_UNSUPPORTED = 'ci_provider_unsupported';
